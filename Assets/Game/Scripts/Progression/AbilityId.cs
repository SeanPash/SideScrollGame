// All player abilities that can be locked or unlocked through progression.
// The first group is the tutorial moveset (taught early, existing animations);
// the second group is the marquee unlocks earned from bosses.
public enum AbilityId
{
    // Tutorial moveset
    WallJump,
    Dash,
    Slide,
    Parry,
    ChargeAttack,

    // Marquee unlocks (boss rewards)
    DoubleJump,
    PhaseDash,
    GroundSlam,
    ReflectParry,
    UltimateBurst
}
